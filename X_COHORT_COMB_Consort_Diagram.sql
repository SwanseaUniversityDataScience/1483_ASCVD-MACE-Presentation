-- Checking ALFs with ASCVD diagnoses from PEDW & WLGP have a record in WDSD
--
WITH GP_PEDW AS
(
SELECT
	*
FROM SAILW1483V.PREP_ALF_WLGP_TYPES

UNION

SELECT
	*
FROM SAILW1483V.PREP_ALF_PEDW_TYPES
)

