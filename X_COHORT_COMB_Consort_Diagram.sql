INSERT INTO SAILW1483V.PREP_ALF_PEDW_TYPES
--
-- Returning ALFs from PEDW with an ASCVD diagnosis between 2000-2023
--
WITH A AS
(
SELECT
DIAG.PROV_UNIT_CD,
DIAG.SPELL_NUM_PE,
DIAG.EPI_NUM,
ICD_TYPE,
ICD.DIAG_CD_123,
ICD.DIAG_DESC_4 
FROM SAILW1483V.EXTRACT_PEDW_DIAG DIAG

JOIN SAILW1483V.PHEN_ASCVD_ICD10 ICD
ON DIAG.DIAG_CD_123  = ICD.DIAG_CD_123 
)
,

B AS
(
SELECT
EPI.PROV_UNIT_CD,
EPI.SPELL_NUM_PE,
ICD_TYPE,
A.DIAG_CD_123,
A.DIAG_DESC_4
FROM A 

JOIN SAILW1483V.EXTRACT_PEDW_EPISODE EPI
ON A.PROV_UNIT_CD = EPI.PROV_UNIT_CD
AND A.SPELL_NUM_PE = EPI.SPELL_NUM_PE
AND A.EPI_NUM = EPI.EPI_NUM
)
,

C AS
(
SELECT
SPELL.ALF_PE,
ICD_TYPE AS TYPE,
DIAG_CD_123 AS CODE,
DIAG_DESC_4 AS DESC,
SPELL.ADMIS_DT AS EVENT_DT
FROM B

JOIN SAILW1483V.EXTRACT_PEDW_SPELL SPELL
ON B.PROV_UNIT_CD = SPELL.PROV_UNIT_CD
AND B.SPELL_NUM_PE = SPELL.SPELL_NUM_PE
)
,

D AS
(
SELECT
*
FROM C

WHERE C.EVENT_DT BETWEEN SAILW1483V.START_DATE AND SAILW1483V.END_DATE	
)
,

E AS
(
SELECT
*,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY EVENT_DT) AS RANK
FROM D
)

SELECT
ALF_PE,
TYPE,
CODE,
DESC,
EVENT_DT
FROM E

WHERE RANK = 1
;
COMMIT;
