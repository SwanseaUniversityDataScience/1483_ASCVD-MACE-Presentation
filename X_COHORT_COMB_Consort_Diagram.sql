WITH A AS
(
SELECT 
ALF_PE,
TYPE
FROM
(
SELECT
ALF_PE,
TYPE,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY FIRST_DATE) AS RANK
FROM
(
SELECT 
DISTINCT ALF_PE,
CASE 
WHEN TYPE = 'IHD' THEN 'DEATH IHD' 
WHEN TYPE = 'ST' THEN 'DEATH ST' 
ELSE NULL
END AS TYPE,
DEATH_DT AS FIRST_DATE
FROM SAILW1483V.PRIOR_CVD_DEATH_COHORT_ALFS
WHERE YEAR(DEATH_DT) >= 2010

UNION 

SELECT 
DISTINCT ALF_PE,
TYPE,
FIRST_DATE
FROM SAILW1483V.COHORT_MASTER_FINAL
WHERE FIRST_YEAR >= 2010
AND TYPE <> 'PAD'
)
)
WHERE RANK = 1
)
,

ALL AS
(
SELECT
COUNT(DISTINCT ALF_PE) AS TOTAL
FROM A
)
,

SPLIT AS
(
SELECT
TYPE,
COUNT(DISTINCT ALF_PE) AS FREQ
FROM A

GROUP BY TYPE
)

SELECT
A.*,
ROUND(FREQ / CAST(ALL.TOTAL AS DECIMAL(31,8)),3)*100 AS PCT
FROM SPLIT A

CROSS JOIN ALL
;


