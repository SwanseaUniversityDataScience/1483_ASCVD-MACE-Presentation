INSERT INTO SAILW1483V.PREP_ALF_WLGP_TYPES
(
--
-- Returning ALFs from WLGP with an ASCVD diagnosis between 2000-2023
--
SELECT
ALF_PE,
TYPE,
CODE,
DESC,
EVENT_DT
FROM
(
SELECT
	GP.ALF_PE,
	READ_TYPE AS TYPE,
	READ_CODE AS CODE,
	C.DESC,
	EVENT_DT,
	ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY EVENT_DT) AS RANK
FROM 
	SAILW1483V.EXTRACT_WLGP_GP_EVENT_CLEANSED GP

JOIN SAILW1483V.PHEN_ASCVD_READ C
	ON GP.EVENT_CD = C.READ_CODE
	
WHERE 
	GP.EVENT_DT BETWEEN SAILW1483V.START_DATE AND SAILW1483V.END_DATE
)
WHERE RANK = 1
);
COMMIT;
