------------------------------------------
--
--Insert into Table
INSERT INTO SAILW1483V.PRIOR_CVD_DEATH_COHORT_BMI_BASELINE

WITH A AS
(
SELECT
B.ALF_PE,
A.DEATH_DT,
EVENT_DT,
EVENT_VAL,
WEIGHT
FROM SAILW1483V.PRIOR_CVD_DEATH_COHORT_BMI B

JOIN SAILW1483V.PRIOR_CVD_DEATH_COHORT_ALFS A
ON B.ALF_PE = A.ALF_PE

WHERE B.EVENT_DT <= DEATH_DT
)

SELECT
ALF_PE,
DEATH_DT,
EVENT_DT,
EVENT_VAL,
WEIGHT
FROM
(
SELECT
*,
ROW_NUMBER() OVER(PARTITION BY ALF_PE ORDER BY EVENT_DT DESC) AS RANK
FROM A
)
WHERE RANK = 1
;
