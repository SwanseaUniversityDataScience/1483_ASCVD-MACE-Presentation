--Insert into Table
INSERT INTO SAILW1483V.PRIOR_CVD_DEATH_COHORT_BMI

WITH A AS
(
SELECT
ALF_PE,
BMI_DT AS EVENT_DT,
BMI_VAL AS EVENT_VAL,
BMI_CAT AS WEIGHT
FROM SAILW1483V.P4_BMI_CLEAN_ADULTS
)

SELECT
ALF_PE,
EVENT_DT,
CASE WHEN EVENT_VAL > 100 THEN NULL ELSE EVENT_VAL END AS EVENT_VAL,
CASE 
WHEN WEIGHT = 'Normal weight' THEN 'N'
WHEN WEIGHT = 'Overweight' THEN 'OW'
WHEN WEIGHT = 'Underweight' THEN 'UW'
WHEN WEIGHT = 'Obese' THEN 'OB'
ELSE 'UN' END AS WEIGHT
FROM A

WHERE EVENT_VAL IS NOT NULL
;
